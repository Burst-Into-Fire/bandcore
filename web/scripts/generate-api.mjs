// Generates src/api/schema.ts from the API's OpenAPI document.
//
// The document is written by the API integration tests (./mvnw verify) to
// api/target/openapi/openapi.json. Override the path with OPENAPI_SPEC.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const webRoot = fileURLToPath(new URL('..', import.meta.url));
const specPath = process.env.OPENAPI_SPEC ?? `${webRoot}../api/target/openapi/openapi.json`;
const outputPath = `${webRoot}src/api/schema.ts`;

const spec = JSON.parse(await readFile(specPath, 'utf8'));
const ast = await openapiTS(spec);
const header =
  '// Generated by `npm run api:generate` from the API OpenAPI document. Do not edit.\n\n';
await writeFile(outputPath, header + astToString(ast));
console.log(`Wrote ${outputPath} from ${specPath}`);
